export function detectLocale(lang: string): Locale {
  const s = lang.toLowerCase();
  if (s.startsWith("zh"))
    return /hant|tw|hk|mo/.test(s) ? "zh-Hant" : "zh-Hans";
  if (s.startsWith("ja")) return "ja";
  if (s.startsWith("ko")) return "ko";
  return "en";
}
